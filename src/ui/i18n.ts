export function initialLang(): Lang {
  try {
    const saved = localStorage.getItem('btt-lang');
    if (saved === 'hu' || saved === 'en') return saved;
  } catch { /* ignore */ }
  return navigator.language?.toLowerCase().startsWith('hu') ? 'hu' : 'en';
}
